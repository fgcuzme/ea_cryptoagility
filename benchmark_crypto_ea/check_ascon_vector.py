from ascon import encrypt, decrypt


# ============================================================
# Same deterministic test vector used by bench_utangle_crypto.c
# ============================================================

key = bytes(range(0x00, 0x10))

nonce = bytes(range(0x10, 0x20))

associated_data = bytes(range(0x20, 0x30))

plaintext = bytes(range(0x40, 0x60))


# Result produced by bench_utangle_crypto.c
cttag_c = bytes.fromhex(
    "7e8977abbd67c794d7e98c32a382a097"
    "d0e85baccb96aa2661fb3743ff977471"
    "3867c1fd57686e73697d47e88edfd58b"
)


print("============================================================")
print("ASCON-128 U-Tangle Python/C cross-check")
print("============================================================")

print("key      =", key.hex())
print("nonce    =", nonce.hex())
print("ad       =", associated_data.hex())
print("plaintext=", plaintext.hex())


# ============================================================
# Python encryption
# ============================================================

cttag_python = encrypt(
    key,
    nonce,
    associated_data,
    plaintext,
    variant="Ascon-128"
)


print("\nC result     =", cttag_c.hex())
print("Python result=", cttag_python.hex())


# ============================================================
# Compare byte by byte
# ============================================================

if cttag_python == cttag_c:

    print("\n[OK] Python and C ciphertext+tag are IDENTICAL.")

else:

    print("\n[ERROR] Python and C results are DIFFERENT.")

    print("\nLengths:")
    print("C      =", len(cttag_c))
    print("Python =", len(cttag_python))

    print("\nByte differences:")

    max_len = max(
        len(cttag_c),
        len(cttag_python)
    )

    for i in range(max_len):

        c_byte = (
            cttag_c[i]
            if i < len(cttag_c)
            else None
        )

        py_byte = (
            cttag_python[i]
            if i < len(cttag_python)
            else None
        )

        if c_byte != py_byte:

            print(
                f"offset {i:02d}: "
                f"C={c_byte!r} "
                f"Python={py_byte!r}"
            )


# ============================================================
# C -> Python decryption test
# ============================================================

plaintext_from_c = decrypt(
    key,
    nonce,
    associated_data,
    cttag_c,
    variant="Ascon-128"
)


print(
    "\nDecrypted C vector with Python =",
    plaintext_from_c.hex()
    if plaintext_from_c is not None
    else None
)


if plaintext_from_c == plaintext:

    print(
        "[OK] Python correctly decrypts "
        "the ciphertext+tag generated by C."
    )

else:

    print(
        "[ERROR] Python cannot reproduce "
        "the C decryption result."
    )


# ============================================================
# Final validation
# ============================================================

if (
    cttag_python == cttag_c
    and plaintext_from_c == plaintext
):

    print("\n============================================================")
    print("FINAL RESULT: ASCON IMPLEMENTATIONS ARE EQUIVALENT")
    print("============================================================")

else:

    print("\n============================================================")
    print("FINAL RESULT: DO NOT USE C BENCHMARK VALUES YET")
    print("============================================================")